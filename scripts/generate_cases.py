def clean_text(t):
    return re.sub(r'\s+', ' ', t).strip()

def parse_cases_from_section(sec_name, s, e):
    sub = part4_text[s:e]
    blocks = re.split(r'\n(?=#{1,3}\s*病例|\n\s*病例\s*\d+)', sub)
    cases = []
    
    for b in blocks:
        b_s = b.strip()
        if not b_s or '第四部分' in b_s or b_s.startswith('## ' + sec_name):
            continue
            
        m_t = re.match(r'^#{0,3}\s*(病例\s*\d+)', b_s)
        case_num = m_t.group(1).replace(' ', '') if m_t else '病例'
        
        # Split by questions
        q_split = re.split(r'#{0,3}\s*临床解剖学问题[:：]?', b_s)
        scenario = q_split[0].strip()
        scenario_lines = [l for l in scenario.split('\n') if not re.match(r'^#{0,3}\s*病例', l.strip())]
        scenario_clean = clean_text(' '.join(scenario_lines))
        
        q_text = q_split[1].strip() if len(q_split) > 1 else ''
        q_items = re.findall(r'(?:^|\n)\s*(\d+)[\.、\s]+([\s\S]*?)(?=(?:\n\s*\d+[\.、\s])|\Z)', q_text)
        questions = [f"{num}. {clean_text(q)}" for num, q in q_items]
        
        # Match with answer database
        matched_db = None
        for db_key, db_val in ANSWER_DATABASE.items():
            for kw in db_val['match']:
                if kw in scenario_clean or kw in q_text:
                    matched_db = db_val
                    break
            if matched_db:
                break
                
        if matched_db:
            case_title = matched_db['title']
            answers = matched_db['answers']
            pearl = matched_db['pearl']
        else:
            case_title = f"{sec_name} · {case_num} 临床解剖学辨析"
            # Generate fallback answers based on question stems
            answers = []
            for q in questions:
                q_pure = re.sub(r'^\d+[\.、\s]+', '', q)
                answers.append(f"【问题解答】：针对「{q_pure}」，需结合{sec_name}局解层次、神经走行、血管回流及深筋膜间隙进行全面定位分析，明确病灶对邻近结构的机械压迫与神经反射机制。")
            pearl = f"密切掌握{sec_name}局部血管、神经分支及筋膜间隙交通是解决该病例的关键解剖学线索。"
            
        cases.append({
            'id': f"CASE-{sec_name}-{case_num}",
            'chapter': sec_name,
            'caseNum': case_num,
            'title': case_title,
            'scenario': scenario_clean,
            'questions': questions,
            'answers': answers,
            'clinicalPearl': pearl
        })
    return cases

